/**
 * BDRSF কাস্টম CameraX ডকুমেন্ট ও ফেস স্ক্যানার।
 * - NID ফ্রন্ট/ব্যাক (1.586:1), পাসপোর্ট A4 স্প্রেড (0.707:1), সাধারণ ডকুমেন্ট ও ফেস লাইভনেস সাপোর্ট করে।
 * - ক্যাপচার করা ফাইল NidProcessorFeature / PassportProcessorFeature / GenericOcrFeature-এ পাঠায়।
 */
class DocumentScannerFeature(
    private val activity: Activity,
    private val rootContainer: ViewGroup,
    private val bridge: AndroidBridge,
    private val onDocumentCapturedListener: (capturedFile: File, scanMode: String, policy: JSONObject, callback: String?) -> Unit
) {

    companion object {
        private const val RC_CAMERA_PERMISSION = 2001
        private const val BANGLADESH_NID_RATIO = 1.586f
        private const val A4_PASSPORT_RATIO = 0.707f
        private const val REQUIRED_STABLE_FRAMES = 6
    }

    private val cameraExecutor: ExecutorService = Executors.newSingleThreadExecutor()
    private var cameraProvider: ProcessCameraProvider? = null
    private var camera: Camera? = null
    private var previewView: PreviewView? = null
    private var imageCapture: ImageCapture? = null
    private var scannerOverlayLayout: FrameLayout? = null
    private var hudOverlayView: View? = null

    private var activeScanMode: String = "nid_front"
    private var activePolicy: JSONObject = JSONObject()
    private var activeCallback: String? = null
    private var isTorchOn: Boolean = false
    private val isCapturing = AtomicBoolean(false)
    private var stableFrameCount: Int = 0

    @Volatile
    private var destroyed: Boolean = false

    @Volatile
    var isScanningActive: Boolean = false
        private set

    private val faceDetector: FaceDetector by lazy {
        val options = FaceDetectorOptions.Builder()
            .setPerformanceMode(FaceDetectorOptions.PERFORMANCE_MODE_FAST)
            .setClassificationMode(FaceDetectorOptions.CLASSIFICATION_MODE_ALL)
            .setLandmarkMode(FaceDetectorOptions.LANDMARK_MODE_NONE)
            .build()
        FaceDetection.getClient(options)
    }

    private val textRecognizer: TextRecognizer by lazy {
        TextRecognition.getClient(TextRecognizerOptions.DEFAULT_OPTIONS)
    }

    private fun resolveNormalizedScanMode(payload: JSONObject): String {
        val rawMode = listOf(
            payload.optString("scanMode", ""),
            payload.optString("mode", ""),
            payload.optString("docCategory", ""),
            payload.optString("documentType", ""),
            payload.optString("docType", "")
        ).firstOrNull { it.isNotBlank() }.orEmpty().trim().lowercase(Locale.ROOT)

        return when {
            rawMode.contains("pass") -> "passport"
            rawMode.contains("face") || rawMode.contains("selfie") || rawMode.contains("live") -> "face_liveness"
            rawMode.contains("back") -> "nid_back"
            rawMode.contains("nid") || rawMode.contains("front") || rawMode.contains("card") -> "nid_front"
            rawMode.contains("utility") || rawMode.contains("bank") || rawMode.contains("tin") ||
                rawMode.contains("bin") || rawMode.contains("vat") || rawMode.contains("bill") ||
                rawMode.contains("statement") || rawMode.contains("generic") -> "generic"
            else -> "nid_front"
        }
    }

    fun startScanner(payload: JSONObject, callback: String?) {
        if (destroyed) return
        if (!hasCameraPermission()) {
            ActivityCompat.requestPermissions(activity, arrayOf(Manifest.permission.CAMERA), RC_CAMERA_PERMISSION)
            return
        }

        if (isScanningActive) return

        activity.runOnUiThread {
            if (destroyed || isScanningActive) return@runOnUiThread
            isScanningActive = true
            isCapturing.set(false)
            stableFrameCount = 0
            isTorchOn = false
            activeCallback = callback
            activePolicy = JSONObject(payload.toString())
            activeScanMode = resolveNormalizedScanMode(activePolicy)

            val customRatio = activePolicy.optDouble("frameRatio", 0.0).toFloat()
            val customGuide = activePolicy.optString("guideText", "")

            buildScannerLayout(customRatio, customGuide)
            bindCameraProvider()
        }
    }

    private fun buildScannerLayout(customRatio: Float, customGuide: String) {
        val density = activity.resources.displayMetrics.density

        scannerOverlayLayout = FrameLayout(activity).apply {
            layoutParams = FrameLayout.LayoutParams(
                FrameLayout.LayoutParams.MATCH_PARENT,
                FrameLayout.LayoutParams.MATCH_PARENT
            )
            setBackgroundColor(Color.BLACK)
        }

        previewView = PreviewView(activity).apply {
            layoutParams = FrameLayout.LayoutParams(
                FrameLayout.LayoutParams.MATCH_PARENT,
                FrameLayout.LayoutParams.MATCH_PARENT
            )
        }
        scannerOverlayLayout?.addView(previewView)

        hudOverlayView = if (isFaceMode()) {
            FaceLivenessHudView(activity)
        } else {
            DocumentCardHudView(activity, activeScanMode, customRatio, customGuide)
        }
        scannerOverlayLayout?.addView(hudOverlayView)

        val topControlsLayout = FrameLayout(activity).apply {
            layoutParams = FrameLayout.LayoutParams(
                FrameLayout.LayoutParams.MATCH_PARENT,
                (60 * density).toInt()
            ).apply {
                topMargin = (35 * density).toInt()
                leftMargin = (20 * density).toInt()
                rightMargin = (20 * density).toInt()
            }
        }

        val closeButton = TextView(activity).apply {
            text = "✕ বাতিল"
            setTextColor(Color.WHITE)
            textSize = 15f
            setPadding((14 * density).toInt(), (8 * density).toInt(), (14 * density).toInt(), (8 * density).toInt())
            setBackgroundColor(Color.parseColor("#80000000"))
            layoutParams = FrameLayout.LayoutParams(
                FrameLayout.LayoutParams.WRAP_CONTENT,
                FrameLayout.LayoutParams.WRAP_CONTENT
            ).apply {
                gravity = Gravity.START or Gravity.CENTER_VERTICAL
            }
            setOnClickListener { stopScanner(isCancelled = true) }
        }
        topControlsLayout.addView(closeButton)

        if (!isFaceMode()) {
            val flashButton = TextView(activity).apply {
                text = "⚡ টর্চ"
                setTextColor(Color.WHITE)
                textSize = 15f
                setPadding((14 * density).toInt(), (8 * density).toInt(), (14 * density).toInt(), (8 * density).toInt())
                setBackgroundColor(Color.parseColor("#80000000"))
                layoutParams = FrameLayout.LayoutParams(
                    FrameLayout.LayoutParams.WRAP_CONTENT,
                    FrameLayout.LayoutParams.WRAP_CONTENT
                ).apply {
                    gravity = Gravity.END or Gravity.CENTER_VERTICAL
                }
                setOnClickListener { toggleTorch(this) }
            }
            topControlsLayout.addView(flashButton)
        }

        scannerOverlayLayout?.addView(topControlsLayout)

        val manualCaptureButton = TextView(activity).apply {
            text = "● ক্যাপচার"
            setTextColor(Color.WHITE)
            textSize = 16f
            setPadding((24 * density).toInt(), (10 * density).toInt(), (24 * density).toInt(), (10 * density).toInt())
            setBackgroundColor(Color.parseColor("#9900E676"))
            layoutParams = FrameLayout.LayoutParams(
                FrameLayout.LayoutParams.WRAP_CONTENT,
                FrameLayout.LayoutParams.WRAP_CONTENT
            ).apply {
                gravity = Gravity.BOTTOM or Gravity.CENTER_HORIZONTAL
                bottomMargin = (30 * density).toInt()
            }
            setOnClickListener {
                if (isScanningActive && isCapturing.compareAndSet(false, true)) {
                    triggerTakePicture()
                }
            }
        }
        scannerOverlayLayout?.addView(manualCaptureButton)

        rootContainer.addView(scannerOverlayLayout)
    }

    private fun bindCameraProvider() {
        val cameraProviderFuture = ProcessCameraProvider.getInstance(activity)
        cameraProviderFuture.addListener({
            if (destroyed || !isScanningActive) return@addListener
            try {
                cameraProvider = cameraProviderFuture.get()
                setupCameraPipelines()
            } catch (e: Exception) {
                Log.e("DocScannerFeature", "Camera provider error", e)
                stopScanner(isCancelled = true)
            }
        }, ContextCompat.getMainExecutor(activity))
    }

    @SuppressLint("UnsafeOptInUsageError")
    private fun setupCameraPipelines() {
        val provider = cameraProvider ?: return
        val lifecycleOwner = activity as? LifecycleOwner ?: return

        val preview = Preview.Builder().build().also {
            it.setSurfaceProvider(previewView?.surfaceProvider)
        }

        imageCapture = ImageCapture.Builder()
            .setCaptureMode(ImageCapture.CAPTURE_MODE_MAXIMIZE_QUALITY)
            .build()

        val imageAnalysis = ImageAnalysis.Builder()
            .setBackpressureStrategy(ImageAnalysis.STRATEGY_KEEP_ONLY_LATEST)
            .build()

        val cameraSelector = if (isFaceMode()) {
            CameraSelector.DEFAULT_FRONT_CAMERA
        } else {
            CameraSelector.DEFAULT_BACK_CAMERA
        }

        imageAnalysis.setAnalyzer(cameraExecutor) { imageProxy ->
            if (!isScanningActive || isCapturing.get() || destroyed) {
                imageProxy.close()
                return@setAnalyzer
            }

            val mediaImage = imageProxy.image
            if (mediaImage == null) {
                imageProxy.close()
                return@setAnalyzer
            }

            val inputImage = InputImage.fromMediaImage(mediaImage, imageProxy.imageInfo.rotationDegrees)
            if (isFaceMode()) {
                analyzeFaceLiveness(inputImage, imageProxy)
            } else {
                analyzeDocumentFrame(inputImage, imageProxy)
            }
        }

        try {
            provider.unbindAll()
            camera = provider.bindToLifecycle(lifecycleOwner, cameraSelector, preview, imageCapture, imageAnalysis)
        } catch (e: Exception) {
            Log.e("DocScannerFeature", "Lifecycle binding failed", e)
            stopScanner(isCancelled = true)
        }
    }

    private fun analyzeFaceLiveness(inputImage: InputImage, imageProxy: androidx.camera.core.ImageProxy) {
        faceDetector.process(inputImage)
            .addOnSuccessListener { faces ->
                if (!isScanningActive || isCapturing.get()) return@addOnSuccessListener
                val faceView = hudOverlayView as? FaceLivenessHudView
                if (faces.isEmpty()) {
                    stableFrameCount = 0
                    faceView?.updateGuidance("ফ্রেমের ভেতরে আপনার মুখমণ্ডল সোজা রাখুন", Color.WHITE, 0f)
                    return@addOnSuccessListener
                }

                val face = faces[0]
                val yaw = face.headEulerAngleY
                val pitch = face.headEulerAngleX
                val leftEye = face.leftEyeOpenProbability ?: -1f
                val rightEye = face.rightEyeOpenProbability ?: -1f

                when {
                    yaw > 12f || yaw < -12f || pitch > 14f || pitch < -12f -> {
                        stableFrameCount = 0
                        faceView?.updateGuidance("মুখমণ্ডল ফ্রেমের মাঝে সোজা রাখুন", Color.YELLOW, 0.25f)
                    }
                    leftEye in 0f..0.55f || rightEye in 0f..0.55f -> {
                        stableFrameCount = 0
                        faceView?.updateGuidance("চোখ পুরোপুরি খোলা রাখুন", Color.parseColor("#FFA500"), 0.5f)
                    }
                    else -> {
                        stableFrameCount++
                        val progress = (stableFrameCount.toFloat() / REQUIRED_STABLE_FRAMES).coerceIn(0f, 1f)
                        faceView?.updateGuidance("স্থির থাকুন... ছবি তোলা ও মিলানো হচ্ছে", Color.parseColor("#00E676"), progress)
                        if (stableFrameCount >= REQUIRED_STABLE_FRAMES && isCapturing.compareAndSet(false, true)) {
                            triggerTakePicture()
                        }
                    }
                }
            }
            .addOnFailureListener { stableFrameCount = 0 }
            .addOnCompleteListener { imageProxy.close() }
    }

    private fun analyzeDocumentFrame(inputImage: InputImage, imageProxy: androidx.camera.core.ImageProxy) {
        val autoCapture = activePolicy.optBoolean("autoCapture", true)
        textRecognizer.process(inputImage)
            .addOnSuccessListener { visionText ->
                if (!isScanningActive || isCapturing.get()) return@addOnSuccessListener
                val cardView = hudOverlayView as? DocumentCardHudView
                val totalLines = visionText.textBlocks.sumOf { it.lines.size }

                if (totalLines >= 4) {
                    stableFrameCount++
                    cardView?.setCardDetected(true)
                    if (autoCapture && stableFrameCount >= REQUIRED_STABLE_FRAMES && isCapturing.compareAndSet(false, true)) {
                        triggerTakePicture()
                    }
                } else {
                    stableFrameCount = 0
                    cardView?.setCardDetected(false)
                }
            }
            .addOnFailureListener { stableFrameCount = 0 }
            .addOnCompleteListener { imageProxy.close() }
    }

    private fun triggerTakePicture() {
        val photoFile = try {
            createTempScanFile()
        } catch (_: Exception) {
            isCapturing.set(false)
            return
        }

        val captureUseCase = imageCapture
        if (captureUseCase == null) {
            isCapturing.set(false)
            return
        }

        val outputOptions = ImageCapture.OutputFileOptions.Builder(photoFile).build()
        captureUseCase.takePicture(
            outputOptions,
            ContextCompat.getMainExecutor(activity),
            object : ImageCapture.OnImageSavedCallback {
                override fun onImageSaved(outputFileResults: ImageCapture.OutputFileResults) {
                    val callback = activeCallback
                    val mode = activeScanMode
                    val policy = JSONObject(activePolicy.toString())

                    stopScanner(isCancelled = false)
                    onDocumentCapturedListener(photoFile, mode, policy, callback)
                }

                override fun onError(exception: ImageCaptureException) {
                    isCapturing.set(false)
                    Toast.makeText(activity, "ক্যাপচার ব্যর্থ হয়েছে: ${exception.message}", Toast.LENGTH_SHORT).show()
                }
            }
        )
    }

    private fun toggleTorch(button: TextView) {
        val cam = camera ?: return
        if (cam.cameraInfo.hasFlashUnit()) {
            isTorchOn = !isTorchOn
            cam.cameraControl.enableTorch(isTorchOn)
            button.text = if (isTorchOn) "☀ বন্ধ" else "⚡ টর্চ"
            button.setBackgroundColor(if (isTorchOn) Color.parseColor("#FFD700") else Color.parseColor("#80000000"))
            button.setTextColor(if (isTorchOn) Color.BLACK else Color.WHITE)
        }
    }

    fun stopScanner(isCancelled: Boolean = false) {
        isScanningActive = false
        isCapturing.set(false)
        (hudOverlayView as? DocumentCardHudView)?.stopAnimation()

        try {
            cameraProvider?.unbindAll()
        } catch (_: Exception) {}

        scannerOverlayLayout?.let {
            rootContainer.removeView(it)
            scannerOverlayLayout = null
        }
        previewView = null
        hudOverlayView = null
        camera = null
        imageCapture = null

        val cb = activeCallback
        activeCallback = null
        if (isCancelled && cb != null) {
            bridge.sendResponseToWeb(
                response = BridgeResponse(
                    action = Actions.START_KYC,
                    status = Status.CANCELLED,
                    message = "Scanning cancelled by user"
                ),
                callbackFunction = cb
            )
        }
    }

    fun destroy() {
        destroyed = true
        stopScanner(isCancelled = false)
        try {
            faceDetector.close()
            textRecognizer.close()
            cameraExecutor.shutdownNow()
        } catch (_: Exception) {}
    }

    private fun hasCameraPermission(): Boolean {
        return ContextCompat.checkSelfPermission(activity, Manifest.permission.CAMERA) == PackageManager.PERMISSION_GRANTED
    }

    private fun isFaceMode(): Boolean {
        return activeScanMode == "face_liveness" || activeScanMode == "selfie"
    }

    @Throws(IOException::class)
    private fun createTempScanFile(): File {
        val timestamp = SimpleDateFormat("yyyyMMdd_HHmmss", Locale.getDefault()).format(Date())
        return File.createTempFile("SCAN_${activeScanMode.uppercase(Locale.ROOT)}_$timestamp", ".jpg", activity.cacheDir)
    }

    private inner class DocumentCardHudView(
        context: Context,
        private val mode: String,
        private val customRatio: Float,
        private val customGuide: String
    ) : View(context) {

        private val shadePaint = Paint().apply { color = Color.parseColor("#B3000000"); style = Paint.Style.FILL }
        private val borderPaint = Paint().apply { color = Color.parseColor("#00E676"); style = Paint.Style.STROKE; strokeWidth = 6f; isAntiAlias = true }
        private val cornerPaint = Paint().apply { color = Color.parseColor("#00E676"); style = Paint.Style.STROKE; strokeWidth = 12f; strokeCap = Paint.Cap.ROUND; isAntiAlias = true }
        private val laserPaint = Paint().apply { isAntiAlias = true; strokeWidth = 6f }
        private val textPaint = Paint().apply {
            color = Color.WHITE
            textSize = 35f
            textAlign = Paint.Align.CENTER
            isAntiAlias = true
            setShadowLayer(8f, 0f, 0f, Color.BLACK)
        }

        private val cardBox = RectF()
        private var laserY = 0f
        private var laserAnimator: ValueAnimator? = null

        override fun onSizeChanged(w: Int, h: Int, oldw: Int, oldh: Int) {
            super.onSizeChanged(w, h, oldw, oldh)
            val effectiveRatio = when {
                customRatio > 0f -> customRatio
                mode == "passport" -> A4_PASSPORT_RATIO
                mode == "generic" -> 0.85f
                else -> BANGLADESH_NID_RATIO
            }

            val boxWidth = if (mode == "passport") w * 0.82f else w * 0.90f
            val boxHeight = (boxWidth / effectiveRatio).coerceAtMost(h * 0.66f)

            val left = (w - boxWidth) / 2f
            val top = (h - boxHeight) / 2f - 25f
            cardBox.set(left, top, left + boxWidth, top + boxHeight)
            startLaserAnimation()
        }

        private fun startLaserAnimation() {
            laserAnimator?.cancel()
            laserAnimator = ValueAnimator.ofFloat(cardBox.top, cardBox.bottom).apply {
                duration = 2200
                repeatCount = ValueAnimator.INFINITE
                repeatMode = ValueAnimator.REVERSE
                interpolator = AccelerateDecelerateInterpolator()
                addUpdateListener {
                    laserY = it.animatedValue as Float
                    invalidate()
                }
                start()
            }
        }

        fun stopAnimation() {
            laserAnimator?.cancel()
            laserAnimator = null
        }

        fun setCardDetected(detected: Boolean) {
            val color = if (detected) Color.parseColor("#00E676") else Color.parseColor("#FFD700")
            borderPaint.color = color
            cornerPaint.color = color
            postInvalidate()
        }

        override fun onDraw(canvas: Canvas) {
            super.onDraw(canvas)
            val w = width.toFloat()
            val h = height.toFloat()

            canvas.drawRect(0f, 0f, w, cardBox.top, shadePaint)
            canvas.drawRect(0f, cardBox.bottom, w, h, shadePaint)
            canvas.drawRect(0f, cardBox.top, cardBox.left, cardBox.bottom, shadePaint)
            canvas.drawRect(cardBox.right, cardBox.top, w, cardBox.bottom, shadePaint)
            canvas.drawRoundRect(cardBox, 20f, 20f, borderPaint)

            val cl = 55f
            canvas.drawLine(cardBox.left, cardBox.top, cardBox.left + cl, cardBox.top, cornerPaint)
            canvas.drawLine(cardBox.left, cardBox.top, cardBox.left, cardBox.top + cl, cornerPaint)
            canvas.drawLine(cardBox.right, cardBox.top, cardBox.right - cl, cardBox.top, cornerPaint)
            canvas.drawLine(cardBox.right, cardBox.top, cardBox.right, cardBox.top + cl, cornerPaint)
            canvas.drawLine(cardBox.left, cardBox.bottom, cardBox.left + cl, cardBox.bottom, cornerPaint)
            canvas.drawLine(cardBox.left, cardBox.bottom, cardBox.left, cardBox.bottom - cl, cornerPaint)
            canvas.drawLine(cardBox.right, cardBox.bottom, cardBox.right - cl, cardBox.bottom, cornerPaint)
            canvas.drawLine(cardBox.right, cardBox.bottom, cardBox.right, cardBox.bottom - cl, cornerPaint)

            if (laserY in cardBox.top..cardBox.bottom) {
                laserPaint.shader = LinearGradient(
                    cardBox.left, laserY, cardBox.right, laserY,
                    intArrayOf(Color.TRANSPARENT, Color.parseColor("#00E676"), Color.TRANSPARENT),
                    null,
                    Shader.TileMode.CLAMP
                )
                canvas.drawLine(cardBox.left + 15f, laserY, cardBox.right - 15f, laserY, laserPaint)
            }

            val guide = if (customGuide.isNotBlank()) {
                customGuide
            } else {
                when (mode) {
                    "nid_front" -> "এনআইডি কার্ডের সামনের অংশ ফ্রেমে সোজা রাখুন"
                    "nid_back" -> "এনআইডি কার্ডের পেছনের অংশ ও বারকোড ফ্রেমে রাখুন"
                    "passport" -> "পাসপোর্টের উভয় পাতা একসাথে A4 ফ্রেমে সোজা রাখুন"
                    else -> "ডকুমেন্টটি ফ্রেমের ভেতরে সোজা রাখুন"
                }
            }
            canvas.drawText(guide, w / 2f, cardBox.bottom + 65f, textPaint)
        }
    }

    private inner class FaceLivenessHudView(context: Context) : View(context) {
        private val clearPaint = Paint().apply { xfermode = PorterDuffXfermode(PorterDuff.Mode.CLEAR); isAntiAlias = true }
        private val backgroundPaint = Paint().apply { color = Color.parseColor("#CC000000"); style = Paint.Style.FILL }
        private val ringBackgroundPaint = Paint().apply { color = Color.parseColor("#44FFFFFF"); style = Paint.Style.STROKE; strokeWidth = 8f; isAntiAlias = true }
        private val ringProgressPaint = Paint().apply { color = Color.parseColor("#00E676"); style = Paint.Style.STROKE; strokeWidth = 10f; strokeCap = Paint.Cap.ROUND; isAntiAlias = true }
        private val textPaint = Paint().apply {
            color = Color.WHITE
            textSize = 42f
            textAlign = Paint.Align.CENTER
            isAntiAlias = true
            setShadowLayer(8f, 0f, 0f, Color.BLACK)
        }

        private val ovalBounds = RectF()
        private var currentGuidance: String = "ফ্রেমের ভেতরে আপনার মুখমণ্ডল সোজা রাখুন"
        private var progressPercent: Float = 0f

        override fun onSizeChanged(w: Int, h: Int, oldw: Int, oldh: Int) {
            super.onSizeChanged(w, h, oldw, oldh)
            setLayerType(LAYER_TYPE_SOFTWARE, null)
            val ovalWidth = w * 0.75f
            val ovalHeight = ovalWidth * 1.35f
            val left = (w - ovalWidth) / 2f
            val top = (h - ovalHeight) / 2f - 40f
            ovalBounds.set(left, top, left + ovalWidth, top + ovalHeight)
        }

        fun updateGuidance(message: String, textColor: Int, progress: Float) {
            currentGuidance = message
            textPaint.color = textColor
            progressPercent = progress
            postInvalidate()
        }

        override fun onDraw(canvas: Canvas) {
            super.onDraw(canvas)
            val w = width.toFloat()
            val h = height.toFloat()
            canvas.drawRect(0f, 0f, w, h, backgroundPaint)
            canvas.drawOval(ovalBounds, clearPaint)
            canvas.drawOval(ovalBounds, ringBackgroundPaint)
            if (progressPercent > 0f) {
                canvas.drawArc(ovalBounds, -90f, progressPercent * 360f, false, ringProgressPaint)
            }
            canvas.drawText(currentGuidance, w / 2f, ovalBounds.bottom + 80f, textPaint)
        }
    }
